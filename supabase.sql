create table if not exists public.scams (
    id bigint generated by default as identity primary key,
    kind text not null check (kind in ('upi', 'domain', 'phone')),
    value text not null,
    category text not null default 'other',
    reports integer not null default 1 check (reports > 0),
    last_seen timestamptz not null default now(),
    constraint scams_kind_value_unique unique (kind, value)
);

alter table public.scams enable row level security;

drop policy if exists "Scam checks are publicly readable" on public.scams;
create policy "Scam checks are publicly readable"
    on public.scams for select
    to anon, authenticated
    using (true);

grant select on public.scams to anon, authenticated;
revoke insert, update, delete on public.scams from anon, authenticated;

create or replace function public.report_scam(
    p_kind text,
    p_value text,
    p_category text default 'other'
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    report_count integer;
begin
    if p_kind not in ('upi', 'domain', 'phone') or length(trim(p_value)) = 0 then
        raise exception 'invalid scam report';
    end if;

    insert into public.scams(kind, value, category, reports, last_seen)
    values (p_kind, lower(trim(p_value)), left(coalesce(p_category, 'other'), 40), 1, now())
    on conflict (kind, value) do update
    set reports = public.scams.reports + 1,
        category = excluded.category,
        last_seen = now()
    returning reports into report_count;

    return report_count;
end;
$$;

revoke all on function public.report_scam(text, text, text) from public, anon, authenticated;
grant execute on function public.report_scam(text, text, text) to service_role;

do $$
begin
    if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
       and not exists (
           select 1 from pg_publication_tables
           where pubname = 'supabase_realtime'
             and schemaname = 'public'
             and tablename = 'scams'
       ) then
        alter publication supabase_realtime add table public.scams;
    end if;
end
$$;

